function choices(a: string, b: string): KnowledgeChoice[] {
  return [
    { id: "principle", label: a, detail: "先抓住它的结构、条件和边界。" },
    { id: "case", label: b, detail: "先从一个具体文本、产品或使用情境进入。" },
    { id: "unsure", label: "还没想清楚", detail: "保留问题，继续浏览后再判断。" },
  ];
}

export function node(
  title: string,
  description: string,
  concept: string,
  context: string,
  examples: [string, string, string],
  misconception: string,
  question: string,
  choiceLabels: [string, string] = ["先理解原理", "先看具体案例"],
): KnowledgeNodeInput {
  return {
    title,
    description,
    conceptTitle: `理解“${title}”的核心`,
    concept: [concept],
    contextTitle: "把它放回完整链路",
    context: [context],
    contextBullets: examples,
    confusionTitle: "最容易混淆的地方",
    confusion: [misconception],
    choiceQuestion: question,
    choices: choices(...choiceLabels),
  };
}

